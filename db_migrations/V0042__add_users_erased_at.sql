-- Пометка стёртого пользователя.
--
-- Задания жёстко ссылаются на автора (jobs.owner_id NOT NULL), поэтому
-- строку пользователя нельзя убрать физически, не потеряв задания.
-- Вместо этого профиль обезличивается, а этот флаг убирает человека
-- из всех лент, списков и поиска — снаружи он исчезает полностью.
ALTER TABLE users ADD COLUMN IF NOT EXISTS erased_at TIMESTAMP;

-- Ленты и списки фильтруют по этому полю на каждом запросе
CREATE INDEX IF NOT EXISTS idx_users_erased_at ON users (erased_at);
