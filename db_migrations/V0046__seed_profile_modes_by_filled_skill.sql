-- Проверка фильтра «Люди»: у части профилей выключаем один из режимов,
-- чтобы убедиться, что вкладки исполнителей и заказчиков показывают
-- разные списки, а не одинаковые.
--
-- Значения выбраны по смыслу профиля: у кого заполнена специальность —
-- тот прежде всего исполнитель. Люди могут поменять это у себя
-- в настройках в любой момент.
UPDATE users
SET as_customer = FALSE
WHERE role = 'member' AND erased_at IS NULL
  AND COALESCE(skill, '') <> ''
  AND done_count = 0
  AND created_count = 0;