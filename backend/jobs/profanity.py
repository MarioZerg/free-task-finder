"""
Замена нецензурной брани в пользовательских текстах.

Найденное ругательство заменяется на «Я тебя Люблю» — вместе с кавычками,
как просили. Текст при этом не режется и сообщение доходит: человек видит,
что его услышали, но грубость до собеседника не долетает.

Русский мат вырастает из небольшого числа корней, поэтому проверяем именно
корни, а не список словоформ — иначе любая приставка или окончание («за-»,
«-ще», «-ватый») проходили бы насквозь.
"""

