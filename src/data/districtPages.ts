export const getDistrictPage = (citySlug?: string, districtSlug?: string): DistrictPage | undefined =>
  DISTRICT_PAGES.find((d) => d.citySlug === citySlug && d.slug === districtSlug);

export const getDistrictPagesByCity = (citySlug: string): DistrictPage[] =>
  DISTRICT_PAGES.filter((d) => d.citySlug === citySlug);

export const countOpenJobsInDistrict = (feed: JobItem[], districtLabel: string): number => {
  const target = districtLabel.trim().toLowerCase();
  return feed.filter((job) => (job.city.split(',')[1] || '').trim().toLowerCase() === target)
    .length;
};