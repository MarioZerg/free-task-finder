/** Варианты ответов для блоков «Вопросы и ответы» на посадочных страницах.
 *
 *  Зачем: раньше на всех 304 страницах стоял один и тот же FAQ слово в слово.
 *  Поисковики считают такие блоки шаблонными и понижают ценность страницы —
 *  при проверке совпадение текста между страницами доходило до 76%.
 *  Здесь по 4–5 формулировок на каждый вопрос: страница берёт вариант по
 *  своему номеру, поэтому соседние города и профессии не выглядят копиями.
 */

/** Детерминированный выбор варианта: одна и та же страница всегда получает
 *  один и тот же текст (важно для поисковой индексации — контент не должен
 *  «прыгать» между визитами робота). */
export const pick = <T,>(list: T[], seed: number, offset = 0): T =>
  list[Math.abs(seed + offset) % list.length];

